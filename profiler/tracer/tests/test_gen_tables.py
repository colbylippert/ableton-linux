def make_tree(root):
    def put(rel, text):
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)

    put("VERSION", "Wine version 11.13\n")
    put("dlls/ntdll/ntsyscalls.h", NTSYSCALLS_H)
    put("dlls/win32u/win32syscalls.h", WIN32SYSCALLS_H)
    put("include/wine/server_protocol.h", SERVER_PROTOCOL_H)
    put("dlls/mmdevapi/unixlib.h", MMDEVAPI_UNIXLIB_H)
    put("dlls/winealsa.drv/unixlib.h", WINEALSA_UNIXLIB_H)
    put("dlls/winscard/unixlib.h", WINSCARD_UNIXLIB_H)
    put("dlls/funky.sys/unixlib.h", FUNKY_UNIXLIB_H)
    put("dlls/nothing/unixlib.h", NOTHING_UNIXLIB_H)


class SyntheticTreeTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        make_tree(cls.tmp.name)
        cls.data = gen.generate(cls.tmp.name, label="synthetic")

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_header(self):
        self.assertEqual(self.data["schema"], gen.SCHEMA)
        self.assertEqual(self.data["wine_version"], "11.13")
        self.assertEqual(self.data["generated_from"]["wine_src"], "synthetic")
        self.assertEqual(self.data["server_protocol_version"], 957)

    def test_win64_table_is_used(self):
        syscalls = self.data["syscalls"]
        self.assertEqual(syscalls["0x0001"], "NtSixtyFour")
        self.assertEqual(syscalls["0x0002"], "NtQueryInformationProcess")
        self.assertEqual(syscalls["0x0046"], "NtYieldExecution")
        self.assertEqual(syscalls["0x14bb"], "NtUserMsgWaitForMultipleObjectsEx")
        self.assertNotIn("NtThirtyTwoOnly", syscalls.values())
        self.assertEqual(self.data["counts"]["syscalls_ntdll"], 4)
        self.assertEqual(self.data["counts"]["syscalls_win32u"], 2)
        self.assertEqual(list(syscalls), sorted(syscalls))

    def test_requests(self):
        self.assertEqual(self.data["requests"], {"0": "new_process", "1": "get_new_process_info", "2": "select",
                                                 "3": "create_event"})

    def test_unixcalls(self):
        unix = self.data["unixcalls"]
        self.assertEqual(unix["mmdevapi"], {"0": "process_attach", "1": "process_detach", "2": "main_loop_start",
                                            "3": "midi_release"})
        self.assertEqual(unix["winealsa"], unix["mmdevapi"])
        self.assertEqual(self.data["unixcall_sources"]["winealsa"]["header"], "dlls/mmdevapi/unixlib.h")
        self.assertEqual(self.data["unixcall_sources"]["winealsa"]["so"], "winealsa.so")
        self.assertEqual(unix["winscard"], {"0": "scard_establish_context", "1": "scard_release_context",
                                            "2": "wow64_scard_status"})
        self.assertEqual(unix["funky"], {"6": "first", "7": "second", "16": "third"})
        self.assertNotIn("nothing", unix)
        warnings = "\n".join(self.data["warnings"])
        self.assertIn("SOME_MACRO", warnings)
        self.assertIn("dlls/nothing/unixlib.h", warnings)

    def test_write_json_is_lf_and_round_trips(self):
        out = os.path.join(self.tmp.name, "out", "table.json")
        gen.write_json(self.data, out)
        with open(out, "rb") as handle:
            raw = handle.read()
        self.assertNotIn(b"\r", raw)
        self.assertTrue(raw.endswith(b"}\n"))
        self.assertEqual(json.loads(raw.decode("utf-8")), self.data)

    def test_main_reports_errors(self):
        with tempfile.TemporaryDirectory() as empty:
            self.assertEqual(gen.main(["--wine-src", empty, "--out", os.path.join(empty, "x.json")]), 1)


class CommittedTableTest(unittest.TestCase):
    """The checked-in table for the 11.13 runtime must carry the ids the validation probe relies on."""

    @classmethod
    def setUpClass(cls):
        with open(TABLE_PATH, "r", encoding="utf-8") as handle:
            cls.table = json.load(handle)

    def test_identity(self):
        self.assertEqual(self.table["schema"], gen.SCHEMA)
        self.assertEqual(self.table["wine_version"], "11.13")
        self.assertEqual(self.table["server_protocol_version"], 957)
        self.assertEqual(self.table["generated_from"]["git_describe"], "series-aceb236")

    def test_known_syscalls(self):
        syscalls = self.table["syscalls"]
        self.assertEqual(syscalls["0x0046"], "NtYieldExecution")
        self.assertEqual(syscalls["0x0031"], "NtQueryPerformanceCounter")
        self.assertEqual(syscalls["0x0048"], "NtCreateEvent")
        self.assertEqual(syscalls["0x0004"], "NtWaitForSingleObject")
        self.assertEqual(syscalls["0x000f"], "NtClose")
        self.assertEqual(syscalls["0x0034"], "NtDelayExecution")
        self.assertEqual(syscalls["0x008b"], "NtCreateThreadEx")
        self.assertEqual(syscalls["0x14bb"], "NtUserMsgWaitForMultipleObjectsEx")
        self.assertEqual(len(set(syscalls.values())), len(syscalls))

    def test_known_requests(self):
        requests = self.table["requests"]
        by_name = {name: int(number) for number, name in requests.items()}
        self.assertEqual(by_name["select"], 29)
        self.assertEqual(by_name["create_event"], 30)
        self.assertEqual(by_name["close_handle"], 21)
        self.assertIn("get_inproc_sync_fd", by_name)
        self.assertEqual(sorted(int(number) for number in requests), list(range(len(requests))))

    def test_known_unixcalls(self):
        unix = self.table["unixcalls"]
        self.assertEqual(unix["winscard"]["0"], "scard_establish_context")
        self.assertEqual(unix["dwrite"]["0"], "process_attach")
        self.assertIn("get_glyph_outline", unix["dwrite"].values())
        self.assertEqual(unix["winealsa"], unix["mmdevapi"])
        self.assertEqual(unix["ntdll"]["3"], "wine_server_call")
        self.assertIn("opengl32", unix)
        self.assertEqual(self.table["warnings"], [])


if __name__ == "__main__":
    unittest.main()
