#!/usr/bin/env python3
"""Generate the id -> name tables the interface tracer needs from a Wine source tree.

    gen_tables.py --wine-src DIR --out FILE [--label TEXT]

Sources (design B section 9):

* ``dlls/ntdll/ntsyscalls.h``   -- ``ALL_SYSCALLS`` inside ``#ifdef _WIN64`` (ids 0x0000-0x0fff).
* ``dlls/win32u/win32syscalls.h`` -- same shape, ids 0x1000+ (``KeAddSystemServiceTable(..., 1)``).
* ``include/wine/server_protocol.h`` -- ``enum request`` (request number = position) and
  ``SERVER_PROTOCOL_VERSION``.
* ``dlls/*/unixlib.h`` -- the unix-call code enum of every module that has one.

Both syscall headers are generated by ``tools/make_specfiles``; every entry has the form
``SYSCALL_ENTRY( 0x0046, NtYieldExecution, 0 )`` or, for the two special cases,
``SYSCALL_ENTRY_NtQueryInformationProcess( 0x0019, NtQueryInformationProcess, 40 )``.  The 32-bit
table (``ALL_SYSCALLS32``) carries the same ids with different argument sizes; WoW64 threads reach
the x86_64 dispatcher with the 64-bit ids, so only the ``_WIN64`` table is emitted.

Unix-call codes are positions in an enum.  The enum is chosen per header as: the first enum whose
name ends in ``func``/``funcs``; else the first enum whose enumerators are mostly ``unix_*``;
else the enum of a directly included ``../<module>/unixlib.h`` (winealsa/wineoss/winecoreaudio
share mmdevapi's).  Initialisers are resolved when they are integers or enumerators defined
earlier in the same header (or its include); anything else stops that enum with a warning.
The table key is the unix library name without ``.so`` (``winealsa.drv`` -> ``winealsa``,
``mountmgr.sys`` -> ``mountmgr``, ``libusb-1.0`` -> ``libusb-1.0``).

Python 3.9+, standard library only, LF output, deterministic for a given tree (no timestamps).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys

SCHEMA = "ableton-linux-wine-tables/v1"

SYSCALL_ENTRY_RE = re.compile(
    r"SYSCALL_ENTRY(?:_[A-Za-z0-9_]+)?\s*\(\s*(0x[0-9a-fA-F]+)\s*,\s*([A-Za-z_][A-Za-z0-9_]*)\s*,\s*(\d+)\s*\)"
)
ENUM_RE = re.compile(r"\benum\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{(.*?)\}\s*;", re.DOTALL)
INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"\.\./([^/"]+)/unixlib\.h"', re.MULTILINE)
FUNCS_NAME_RE = re.compile(r"funcs?$", re.IGNORECASE)
INT_RE = re.compile(r"^(?:0[xX][0-9a-fA-F]+|\d+)$")
VERSION_RE = re.compile(r"^Wine version\s+(\S+)")

MODULE_SUFFIXES = (".drv", ".sys", ".ds", ".dll", ".exe")


class TableError(Exception):
    pass


def read_text(path: str) -> str:
    with open(path, "r", encoding="utf-8", errors="replace", newline="") as handle:
        return handle.read()


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.DOTALL)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def win64_region(text: str):
    """Return the text between ``#ifdef _WIN64`` and its matching ``#else``/``#endif``, or None."""
    lines = text.split("\n")
    depth = 0
    start = None
    for index, line in enumerate(lines):
        stripped = line.strip()
        if start is None:
            if re.match(r"#\s*ifdef\s+_WIN64\b", stripped):
                start = index + 1
                depth = 1
            continue
        if re.match(r"#\s*if(?:def|ndef)?\b", stripped):
            depth += 1
        elif re.match(r"#\s*endif\b", stripped):
            depth -= 1
            if depth == 0:
                return "\n".join(lines[start:index])
        elif depth == 1 and re.match(r"#\s*else\b", stripped):
            return "\n".join(lines[start:index])
    return None


def parse_syscalls(text: str, warnings: list, label: str) -> dict:
    """Return {id(int): name} from a make_specfiles syscall header."""
    region = win64_region(text)
    if region is None:
        warnings.append("%s: no '#ifdef _WIN64' table; using every SYSCALL_ENTRY in the file" % label)
        region = text
    table = {}
    for match in SYSCALL_ENTRY_RE.finditer(region):
        sid = int(match.group(1), 16)
        name = match.group(2)
        if sid in table and table[sid] != name:
            raise TableError("%s: id 0x%04x maps to both %s and %s" % (label, sid, table[sid], name))
        table[sid] = name
    if not table:
        raise TableError("%s: no SYSCALL_ENTRY lines found" % label)
    return table


def parse_requests(text: str):
    """Return ({number: name}, protocol_version, nb_requests) from server_protocol.h."""
    match = re.search(r"\benum\s+request\s*\{(.*?)\}\s*;", strip_comments(text), re.DOTALL)
    if not match:
        raise TableError("server_protocol.h: 'enum request' not found")
    table = {}
    nb_requests = None
    number = 0
    for item in match.group(1).split(","):
        item = item.strip()
        if not item:
            continue
        if "=" in item:
            raise TableError("server_protocol.h: unexpected initialiser in enum request: %r" % item)
        if not item.startswith("REQ_"):
            raise TableError("server_protocol.h: unexpected enumerator %r" % item)
        name = item[len("REQ_"):]
        if name == "NB_REQUESTS":
            nb_requests = number
            continue
        table[number] = name
        number += 1
    version = re.search(r"#\s*define\s+SERVER_PROTOCOL_VERSION\s+(\d+)", text)
    if not version:
        raise TableError("server_protocol.h: SERVER_PROTOCOL_VERSION not found")
    return table, int(version.group(1)), nb_requests


def parse_enum_body(body: str, symbols: dict, warnings: list, label: str):
    """Return [(name, value)] for an enum body; ``symbols`` resolves earlier enumerators."""
    items = []
    body = "\n".join(line for line in body.split("\n") if not line.strip().startswith("#"))
    value = -1
    for raw in body.split(","):
        item = raw.strip()
        if not item:
            continue
        name, _, init = item.partition("=")
        name = name.strip()
        init = init.strip()
        if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name):
            warnings.append("%s: cannot parse enumerator %r; enum truncated" % (label, item))
            break
        if init:
            if INT_RE.match(init):
                value = int(init, 0)
            elif init in symbols:
                value = symbols[init]
            else:
                warnings.append("%s: unresolved initialiser %r; enum truncated" % (label, item))
                break
        else:
            value += 1
        symbols[name] = value
        items.append((name, value))
    return items


def choose_funcs_enum(enums: list):
    """Pick the unix-call code enum among [(name, items)] parsed from one header."""
    for name, items in enums:
        if FUNCS_NAME_RE.search(name):
            return name, items
    for name, items in enums:
        if items and sum(1 for item, _ in items if item.startswith("unix_")) * 2 >= len(items):
            return name, items
    return None, None


def module_key(dll_dir: str) -> str:
    for suffix in MODULE_SUFFIXES:
        if dll_dir.endswith(suffix):
            return dll_dir[: -len(suffix)]
    return dll_dir


def code_name(enumerator: str) -> str:
    return enumerator[5:] if enumerator.startswith("unix_") else enumerator


def parse_unixlib(path: str, warnings: list):
    """Return (enum_name, [(name, value)], include_module_or_None) for one unixlib.h."""
    raw = read_text(path)
    text = strip_comments(raw)
    symbols = {}
    enums = []
    label = os.path.relpath(path).replace(os.sep, "/")
    for match in ENUM_RE.finditer(text):
        enums.append((match.group(1), parse_enum_body(match.group(2), symbols, warnings, label)))
    include = INCLUDE_RE.search(raw)
    name, items = choose_funcs_enum(enums)
    return name, items, (include.group(1) if include else None)


def parse_all_unixlibs(wine_src: str, warnings: list):
    dlls_dir = os.path.join(wine_src, "dlls")
    found = {}
    for dll_dir in sorted(os.listdir(dlls_dir)):
        path = os.path.join(dlls_dir, dll_dir, "unixlib.h")
        if os.path.isfile(path):
            found[dll_dir] = parse_unixlib(path, warnings)
    tables = {}
    sources = {}
    for dll_dir in sorted(found):
        name, items, include = found[dll_dir]
        origin = dll_dir
        if items is None and include and include in found and found[include][1] is not None:
            name, items, _ = found[include]
            origin = include
        if items is None:
            warnings.append("dlls/%s/unixlib.h: no unix-call code enum found; skipped" % dll_dir)
            continue
        key = module_key(dll_dir)
        codes = {}
        for enumerator, value in items:
            if value < 0:
                continue
            if enumerator.endswith("_count") or enumerator.endswith("_COUNT"):
                continue
            codes.setdefault(str(value), code_name(enumerator))
        tables[key] = codes
        sources[key] = {
            "dll": dll_dir,
            "so": key + ".so",
            "header": "dlls/%s/unixlib.h" % origin,
            "enum": name,
            "count": len(codes),
        }
    return tables, sources


def git_identity(wine_src: str):
    identity = {}
    for key, args in (("git_head", ["rev-parse", "HEAD"]), ("git_describe", ["describe", "--tags", "--always"])):
        try:
            out = subprocess.run(
                ["git", "-C", wine_src] + args, capture_output=True, text=True, timeout=30, check=False
            )
        except (OSError, subprocess.SubprocessError):
            out = None
        if out is not None and out.returncode == 0 and out.stdout.strip():
            identity[key] = out.stdout.strip()
    if "git_head" not in identity:
        head_path = os.path.join(wine_src, ".git", "HEAD")
        if os.path.isfile(head_path):
            head = read_text(head_path).strip()
            if head.startswith("ref: "):
                ref_path = os.path.join(wine_src, ".git", head[5:])
                if os.path.isfile(ref_path):
                    identity["git_head"] = read_text(ref_path).strip()
            elif head:
                identity["git_head"] = head
    return identity


def wine_version(wine_src: str) -> str:
    path = os.path.join(wine_src, "VERSION")
    if not os.path.isfile(path):
        raise TableError("%s: VERSION file missing; is this a Wine source tree?" % wine_src)
    match = VERSION_RE.match(read_text(path).strip())
    if not match:
        raise TableError("%s: unexpected VERSION content %r" % (path, read_text(path).strip()))
    return match.group(1)


def generate(wine_src: str, label: str = None) -> dict:
    warnings = []
    version = wine_version(wine_src)
    files = {
        "ntdll": "dlls/ntdll/ntsyscalls.h",
        "win32u": "dlls/win32u/win32syscalls.h",
        "protocol": "include/wine/server_protocol.h",
    }
    for key, rel in files.items():
        if not os.path.isfile(os.path.join(wine_src, rel)):
            raise TableError("%s: %s missing" % (wine_src, rel))
    ntdll = parse_syscalls(read_text(os.path.join(wine_src, files["ntdll"])), warnings, files["ntdll"])
    win32u = parse_syscalls(read_text(os.path.join(wine_src, files["win32u"])), warnings, files["win32u"])
    bad = [sid for sid in ntdll if sid >= 0x1000]
    if bad:
        raise TableError("ntsyscalls.h: ids >= 0x1000 found: %s" % ", ".join("0x%04x" % sid for sid in bad))
    bad = [sid for sid in win32u if not 0x1000 <= sid < 0x2000]
    if bad:
        raise TableError("win32syscalls.h: ids outside 0x1000-0x1fff: %s" % ", ".join("0x%04x" % sid for sid in bad))
    syscalls = {}
    for table in (ntdll, win32u):
        for sid in sorted(table):
            syscalls["0x%04x" % sid] = table[sid]
    requests, protocol_version, nb_requests = parse_requests(read_text(os.path.join(wine_src, files["protocol"])))
    if nb_requests is not None and nb_requests != len(requests):
        raise TableError("server_protocol.h: REQ_NB_REQUESTS=%d but %d requests parsed" % (nb_requests, len(requests)))
    unixcalls, sources = parse_all_unixlibs(wine_src, warnings)
    identity = git_identity(wine_src)
    generated_from = {
        "wine_src": label or os.path.basename(os.path.abspath(wine_src)),
        "files": [files["ntdll"], files["win32u"], files["protocol"], "dlls/*/unixlib.h"],
        "generator": "profiler/tracer/gen_tables.py",
    }
    generated_from.update(identity)
    return {
        "schema": SCHEMA,
        "wine_version": version,
        "generated_from": generated_from,
        "server_protocol_version": protocol_version,
        "counts": {
            "syscalls_ntdll": len(ntdll),
            "syscalls_win32u": len(win32u),
            "requests": len(requests),
            "unixcall_modules": len(unixcalls),
            "unixcall_codes": sum(len(codes) for codes in unixcalls.values()),
        },
        "syscalls": syscalls,
        "requests": {str(number): requests[number] for number in sorted(requests)},
        "unixcalls": unixcalls,
        "unixcall_sources": sources,
        "warnings": warnings,
    }


def write_json(data: dict, out: str) -> None:
    text = json.dumps(data, indent=1, ensure_ascii=True) + "\n"
    if out == "-":
        sys.stdout.write(text)
        return
    directory = os.path.dirname(os.path.abspath(out))
    os.makedirs(directory, exist_ok=True)
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    os.replace(tmp, out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--wine-src", required=True, help="patched Wine source tree")
    parser.add_argument("--out", required=True, help="output JSON file ('-' for stdout)")
    parser.add_argument("--label", help="value recorded as generated_from.wine_src (default: directory name)")
    args = parser.parse_args(argv)
    try:
        data = generate(args.wine_src, args.label)
    except (TableError, OSError) as exc:
        print("gen_tables: %s" % exc, file=sys.stderr)
        return 1
    write_json(data, args.out)
    for warning in data["warnings"]:
        print("gen_tables: warning: %s" % warning, file=sys.stderr)
    counts = data["counts"]
    print(
        "gen_tables: wine %s protocol %d: %d ntdll + %d win32u syscalls, %d requests, %d unix-call codes in %d modules"
        % (
            data["wine_version"],
            data["server_protocol_version"],
            counts["syscalls_ntdll"],
            counts["syscalls_win32u"],
            counts["requests"],
            counts["unixcall_codes"],
            counts["unixcall_modules"],
        ),
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
