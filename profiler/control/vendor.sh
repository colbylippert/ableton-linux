#!/usr/bin/env bash
# Vendor the pinned AbletonOSC commit into vendor/AbletonOSC/. The GitHub
# tarball is cached outside the repo and checked against the pinned sha256.
# Only the files the Remote Script needs are extracted (no tests/, client/,
# .github/, run-console.py). VENDOR.txt records the origin and the sha256 of
# every vendored file; --check compares the tree against it without network.
# Re-running with the same pin writes nothing.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
upstream="https://github.com/ideoforms/AbletonOSC"
commit="0ca68214bd62c9b5cb641ca34006cfd70ba94430"
tarball_url="$upstream/archive/$commit.tar.gz"
tarball_sha256="68c1ced7b9fbe0c50bacd2cbfa86a604d6c74e8080cb0e999f63ed84d62d735e"
licence="MIT (LICENSE.md kept)"
extracted=(LICENSE.md README.md __init__.py manager.py abletonosc/ pythonosc/)
dest="$here/vendor/AbletonOSC"
record="$here/VENDOR.txt"
scratch="${XDG_CACHE_HOME:-$HOME/.cache}/profiler/downloads"
check=0

usage()
{
    cat <<'EOF'
usage: profiler/control/vendor.sh [--scratch DIR] [--check]

  --scratch DIR   download and extraction directory (default ~/.cache/profiler/downloads)
  --check         verify vendor/AbletonOSC/ against VENDOR.txt; nothing is downloaded

The pinned commit and tarball sha256 are at the top of this script. VENDOR.txt
is generated; bump the pin here and re-run to update the vendored tree.
EOF
}

fail()
{
    printf 'vendor: %s\n' "$*" >&2
    exit 1
}

while [ $# -gt 0 ]; do
    case "$1" in
        --scratch)
            [ $# -ge 2 ] || fail "--scratch needs a directory"
            scratch="$2"
            shift 2
            ;;
        --check) check=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; fail "unknown option: $1" ;;
    esac
done

# sha256sum prints "hash  name" on Linux and "hash *name" on Git Bash.
sha256_of()
{
    sha256sum -- "$1" | cut -d' ' -f1
}

# "hash  relative/path" for every vendored file in a stable order. Bytecode and
# logs/ are runtime leftovers, never part of the vendored tree.
tree_sums()
{
    (cd "$1" && find . -type f ! -name '*.pyc' ! -path './logs/*' ! -path '*/__pycache__/*' -print0 \
        | LC_ALL=C sort -z | xargs -0 -r sha256sum --) \
        | sed 's/^\([0-9a-f]\{64\}\) [ *]\.\//\1  /'
}

check_tree()
{
    local recorded present
    [ -f "$record" ] || fail "$record is missing; run vendor.sh first"
    [ -d "$dest" ] || fail "$dest is missing; run vendor.sh first"
    grep -qx "commit: $commit" "$record" || fail "VENDOR.txt does not record commit $commit"
    recorded="$(grep -E '^[0-9a-f]{64}  ' "$record")" || fail "VENDOR.txt has no file list"
    present="$(tree_sums "$dest")"
    if [ "$recorded" != "$present" ]; then
        diff <(printf '%s\n' "$recorded") <(printf '%s\n' "$present") >&2 || true
        fail "vendor/AbletonOSC/ differs from VENDOR.txt (< recorded, > present)"
    fi
    printf 'vendor: OK, %d files match VENDOR.txt\n' "$(printf '%s\n' "$recorded" | wc -l)"
}

if [ "$check" = 1 ]; then
    check_tree
    exit 0
fi

for tool in curl tar sha256sum; do
    command -v "$tool" >/dev/null 2>&1 || fail "$tool is required"
done

mkdir -p -- "$scratch"
tarball="$scratch/AbletonOSC-$commit.tar.gz"
if [ -f "$tarball" ] && [ "$(sha256_of "$tarball")" = "$tarball_sha256" ]; then
    echo "using cached $tarball"
else
    echo "downloading $tarball_url"
    curl -fsSL --retry 3 -o "$tarball.part" "$tarball_url" || fail "download failed: $tarball_url"
    mv -f -- "$tarball.part" "$tarball"
fi
actual="$(sha256_of "$tarball")"
[ "$actual" = "$tarball_sha256" ] \
    || fail "tarball sha256 mismatch: expected $tarball_sha256, got $actual; the upstream archive changed, refusing"

# Extract into a fresh directory next to the cache, never under the repo.
tmp="$(mktemp -d -- "$scratch/extract.XXXXXX")"
trap 'rm -rf -- "$tmp" "$tmp.record"' EXIT
members=()
for path in "${extracted[@]}"; do
    members+=("AbletonOSC-$commit/${path%/}")
done
tar -xzf "$tarball" -C "$tmp" --strip-components=1 "${members[@]}" || fail "extraction failed"
for path in "${extracted[@]}"; do
    [ -e "$tmp/$path" ] || fail "$path is missing from the tarball; the upstream layout changed"
done
find "$tmp" -type d -name __pycache__ -prune -exec rm -rf -- {} +
find "$tmp" -type f -name '*.pyc' -delete

sums="$(tree_sums "$tmp")"
{
    printf '# Generated by profiler/control/vendor.sh; verify with: profiler/control/vendor.sh --check\n'
    printf 'upstream: %s\n' "$upstream"
    printf 'commit: %s\n' "$commit"
    printf 'tarball: %s\n' "$tarball_url"
    printf 'tarball_sha256: %s\n' "$tarball_sha256"
    printf 'date: %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf 'licence: %s\n' "$licence"
    printf 'extracted: %s\n' "${extracted[*]}"
    printf 'files:\n'
    printf '%s\n' "$sums"
} > "$tmp.record"

# Same files and same record apart from the date: leave the repo untouched.
if [ -d "$dest" ] && [ -f "$record" ] && [ "$(tree_sums "$dest")" = "$sums" ] \
    && cmp -s <(grep -v '^date: ' "$record") <(grep -v '^date: ' "$tmp.record"); then
    echo "vendor/AbletonOSC already matches $commit; nothing written"
    exit 0
fi
rm -rf -- "$dest"
mkdir -p -- "$dest"
cp -R -p -- "$tmp/." "$dest/"
cp -- "$tmp.record" "$record"
echo "vendored AbletonOSC@${commit:0:7} into ${dest#"$here/"} ($(printf '%s\n' "$sums" | wc -l) files)"
